export interface HiddenSource { term: string; why: string }

export interface AllergenDef {
  id: AllergenId;
  label: string;
  /** Plain words shown beside the label so a parent sees what the item covers. */
  covers: string;
  /** Words that name the allergen itself. A match in the menu text means "Avoid". */
  direct: string[];
  /** Phrases removed before direct matching (e.g. "coconut milk" is not dairy). */
  ignore?: string[];
  /** Words matched inside longer words (German compounds). Filled from multilingual.ts. */
  loose?: string[];
  /** Words matched with accents kept (Vietnamese). Filled from multilingual.ts. */
  exact?: string[];
  /** Hidden-source entries matched with accents kept (Vietnamese). */
  hiddenExact?: HiddenSource[];
  /** Dishes / sauces that often hide the allergen. A match means "Ask the kitchen". */
  hidden: HiddenSource[];
}

